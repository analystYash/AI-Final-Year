export function getTranslation(lang, keyOrText) {
  if (!keyOrText) return '';
  const normalizedLang = (lang || 'english').toLowerCase();
  const langObj = translations[normalizedLang] || translations.english;
  
  // 1. Direct match
  if (langObj[keyOrText]) return langObj[keyOrText];
  
  // 2. Trimmed match
  const trimmed = typeof keyOrText === 'string' ? keyOrText.trim() : keyOrText;
  if (langObj[trimmed]) return langObj[trimmed];
  
  // 3. Lowercase match
  const lower = typeof trimmed === 'string' ? trimmed.toLowerCase() : '';
  if (langObj[lower]) return langObj[lower];
  
  // 4. English fallback
  if (translations.english[keyOrText]) return translations.english[keyOrText];
  if (translations.english[trimmed]) return translations.english[trimmed];
  if (translations.english[lower]) return translations.english[lower];
  
  // 5. Return original string
  return keyOrText;
}

export function translateText(text, lang) {
  return getTranslation(lang, text);
}

